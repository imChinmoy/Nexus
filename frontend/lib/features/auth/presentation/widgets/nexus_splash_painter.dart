  static const _nd2RKt = [0.0000, 0.1071, 0.1250, 0.1429, 0.1607, 0.1786, 0.1964, 0.2143, 1.0000];
  static const _nd2RV = [0.0000, 0.0000, 1.5400, 3.3400, 4.3800, 4.8500, 4.9900, 5.0000, 5.0000];
  static const _nd2OpKt = [0.0000, 0.1071, 0.1250, 0.1429, 0.1607, 0.1786, 0.1875, 1.0000];
  static const _nd2OpV = [0.0000, 0.0000, 0.1500, 0.4000, 0.6500, 0.9000, 1.0000, 1.0000];
  static const _nd3RKt = [0.0000, 0.0893, 0.1071, 0.1250, 0.1429, 0.1607, 0.1786, 0.1875, 1.0000];
  static const _nd3RV = [0.0000, 0.0000, 1.9700, 3.6000, 4.5100, 4.9000, 5.0000, 5.0000, 5.0000];
  static const _nd3OpKt = [0.0000, 0.0893, 0.1071, 0.1250, 0.1429, 0.1607, 0.1696, 1.0000];
  static const _nd3OpV = [0.0000, 0.0000, 0.2000, 0.4500, 0.7000, 0.9500, 1.0000, 1.0000];
  static const _nd4RKt = [0.0000, 0.1339, 0.1518, 0.1696, 0.1875, 0.2054, 0.2232, 0.2321, 1.0000];
  static const _nd4RV = [0.0000, 0.0000, 2.1700, 3.7200, 4.5700, 4.9200, 5.0000, 5.0000, 5.0000];
  static const _nd4OpKt = [0.0000, 0.1339, 0.1518, 0.1696, 0.1875, 0.2054, 0.2143, 1.0000];
  static const _nd4OpV = [0.0000, 0.0000, 0.2250, 0.4750, 0.7250, 0.9750, 1.0000, 1.0000];
  static const _nodeCoords = [
    Offset(256.0, 256.0),
    Offset(150.0, 142.0),
    Offset(150.0, 370.0),
    Offset(362.0, 142.0),
    Offset(362.0, 370.0),
  ];

  @override
  void paint(Canvas canvas, Size size) {
    if (size.width <= 0 || size.height <= 0) return;

    final t = progress.clamp(0.0, 1.0);

    canvas.save();
    final scale = min(size.width, size.height) / 512.0;
    canvas.translate((size.width - 512 * scale) / 2, (size.height - 512 * scale) / 2);
    canvas.scale(scale, scale);

    final nShader = ui.Gradient.linear(
      const Offset(150, 370),
      const Offset(362, 142),
      const [Color(0xFF1687FF), Color(0xFF77D8FF)],
    );

    final wedgeShader = ui.Gradient.radial(
      const Offset(256, 256),
      240,
      const [Color(0x0077D8FF), Color(0xE677D8FF)],
      const [0.0, 1.0],
    );

    final hBeamShader = ui.Gradient.linear(
      const Offset(96, 0),
      const Offset(416, 0),
      const [Color(0x0077D8FF), Color(0xFF77D8FF), Color(0x0077D8FF)],
      const [0.0, 0.5, 1.0],
    );

    final vBeamShader = ui.Gradient.linear(
      const Offset(0, 96),
      const Offset(0, 416),
      const [Color(0x0077D8FF), Color(0xFF77D8FF), Color(0x0077D8FF)],
      const [0.0, 0.5, 1.0],
    );

    // 1. Radar
    final radarOp = _interp(t, _radarOpKt, _radarOpV);
    if (radarOp > 0.001) {
      final radarRot = _interp(t, _radarRotKt, _radarRotV);
      canvas.save();
      canvas.translate(256, 256);
      canvas.rotate(radarRot * pi / 180.0);
      canvas.translate(-256, -256);
      final radarPath = Path()
        ..moveTo(256, 256)
        ..lineTo(256, 16)
        ..arcTo(
          Rect.fromCircle(center: const Offset(256, 256), radius: 240),
          -pi / 2,
          pi / 3,
          false,
        )
        ..close();
      canvas.drawPath(
        radarPath,
        Paint()
          ..shader = wedgeShader
          ..color = Colors.white.withValues(alpha: radarOp),
      );
      canvas.restore();
    }

    // 2. Lattice
    final latOp = _interp(t, _latOpKt, _latOpV);
    if (latOp > 0.001) {
      final latRot = _interp(t, _latRotKt, _latRotV);
      canvas.save();
      canvas.translate(256, 256);
      canvas.rotate(latRot * pi / 180.0);
      canvas.translate(-256, -256);
      final latPaint = Paint()
        ..color = const Color(0xFF77D8FF).withValues(alpha: latOp)
        ..style = PaintingStyle.fill;
      for (final pt in _latCircles) {
        canvas.drawCircle(pt, 1.6, latPaint);
      }
      canvas.restore();
    }

    // 3. Ticks
    final ticksOp = _interp(t, _ticksOpKt, _ticksOpV);
    if (ticksOp > 0.001) {
      final ticksRot = _interp(t, _ticksRotKt, _ticksRotV);
      canvas.save();
      canvas.translate(256, 256);
      canvas.rotate(ticksRot * pi / 180.0);
      canvas.translate(-256, -256);
      final tickPaint = Paint()
        ..color = const Color(0xFF77D8FF).withValues(alpha: ticksOp)
        ..strokeWidth = 1.0
        ..style = PaintingStyle.stroke;
      for (final line in _tickLines) {
        canvas.drawLine(line[0], line[1], tickPaint);
      }
      canvas.restore();
    }

    // 4. Dash ring A
    final raOp = _interp(t, _raOpKt, _raOpV);
    if (raOp > 0.001) {
      final raRot = _interp(t, _raRotKt, _raRotV);
      canvas.save();
      canvas.translate(256, 256);
      canvas.rotate(raRot * pi / 180.0);
      canvas.translate(-256, -256);
      final raPaint = Paint()
        ..color = const Color(0xFF77D8FF).withValues(alpha: raOp)
        ..strokeWidth = 1.5
        ..style = PaintingStyle.stroke;
      final rectA = Rect.fromCircle(center: const Offset(256, 256), radius: 120);
      const dashArc = 6.0 / 120.0;
      const stepArc = 16.0 / 120.0;
      for (double a = 0; a < 2 * pi; a += stepArc) {
        canvas.drawArc(rectA, a, dashArc, false, raPaint);
      }
      canvas.restore();
    }

    // 5. Dash ring B
    final rbOp = _interp(t, _rbOpKt, _rbOpV);
    if (rbOp > 0.001) {
      final rbRot = _interp(t, _rbRotKt, _rbRotV);
      canvas.save();
      canvas.translate(256, 256);
      canvas.rotate(rbRot * pi / 180.0);
      canvas.translate(-256, -256);
      final rbPaint = Paint()
        ..color = const Color(0xFF77D8FF).withValues(alpha: rbOp)
        ..strokeWidth = 1.0
        ..style = PaintingStyle.stroke;
      final rectB = Rect.fromCircle(center: const Offset(256, 256), radius: 170);
      const dashArcB = 2.0 / 170.0;
      const stepArcB = 9.0 / 170.0;
      for (double a = 0; a < 2 * pi; a += stepArcB) {
        canvas.drawArc(rectB, a, dashArcB, false, rbPaint);
      }
      canvas.restore();
    }

    // 6. Orbit Ring
    final orbOp = _interp(t, _orbOpKt, _orbOpV);
    if (orbOp > 0.001) {
      canvas.drawCircle(
        const Offset(256, 256),
        206,
        Paint()
          ..color = const Color(0xFF77D8FF).withValues(alpha: orbOp)
          ..strokeWidth = 1.2
          ..style = PaintingStyle.stroke,
      );
    }

    // 7. Pulses
    final p1Op = _interp(t, _p1OpKt, _p1OpV);
    if (p1Op > 0.001) {
      final p1R = _interp(t, _p1RKt, _p1RV);
      canvas.drawCircle(
        const Offset(256, 256),
        p1R,
        Paint()
          ..color = const Color(0xFF77D8FF).withValues(alpha: p1Op)
          ..strokeWidth = 1.0
          ..style = PaintingStyle.stroke,
      );
    }
    final p2Op = _interp(t, _p2OpKt, _p2OpV);
    if (p2Op > 0.001) {
      final p2R = _interp(t, _p2RKt, _p2RV);
      canvas.drawCircle(
        const Offset(256, 256),
        p2R,
        Paint()
          ..color = const Color(0xFF77D8FF).withValues(alpha: p2Op)
          ..strokeWidth = 1.0
          ..style = PaintingStyle.stroke,
      );
    }

    // 8. Network lines
    final netOps = [
      _interp(t, _net0OpKt, _net0OpV),
      _interp(t, _net1OpKt, _net1OpV),
      _interp(t, _net2OpKt, _net2OpV),
      _interp(t, _net3OpKt, _net3OpV),
      _interp(t, _net4OpKt, _net4OpV),
      _interp(t, _net5OpKt, _net5OpV),
    ];
    final netDashes = [
      _interp(t, _net0DashKt, _net0DashV),
      _interp(t, _net1DashKt, _net1DashV),
      _interp(t, _net2DashKt, _net2DashV),
      _interp(t, _net3DashKt, _net3DashV),
      _interp(t, _net4DashKt, _net4DashV),
      _interp(t, _net5DashKt, _net5DashV),
    ];
    for (int i = 0; i < 6; i++) {
      if (netOps[i] > 0.001) {
        final drawFraction = (1.0 - netDashes[i]).clamp(0.0, 1.0);
        if (drawFraction > 0.001) {
          final p0 = _netCoords[i][0];
          final p1 = _netCoords[i][1];
          final currentEnd = Offset(
            p0.dx + (p1.dx - p0.dx) * drawFraction,
            p0.dy + (p1.dy - p0.dy) * drawFraction,
          );
          canvas.drawLine(
            p0,
            currentEnd,
            Paint()
              ..color = const Color(0xFF1687FF).withValues(alpha: netOps[i])
              ..strokeWidth = 1.0
              ..strokeCap = StrokeCap.round,
          );
        }
      }
    }

    // 9. Junctions
    final juncOps = [
      _interp(t, _junc0OpKt, _junc0OpV),
      _interp(t, _junc1OpKt, _junc1OpV),
      _interp(t, _junc2OpKt, _junc2OpV),
      _interp(t, _junc3OpKt, _junc3OpV),
      _interp(t, _junc4OpKt, _junc4OpV),
      _interp(t, _junc5OpKt, _junc5OpV),
    ];
    final juncRs = [
      _interp(t, _junc0RKt, _junc0RV),
      _interp(t, _junc1RKt, _junc1RV),
      _interp(t, _junc2RKt, _junc2RV),
      _interp(t, _junc3RKt, _junc3RV),
      _interp(t, _junc4RKt, _junc4RV),
      _interp(t, _junc5RKt, _junc5RV),
    ];
    for (int i = 0; i < 6; i++) {
      if (juncOps[i] > 0.001 && juncRs[i] > 0.05) {
        canvas.drawCircle(
          _juncCoords[i],
          juncRs[i],
          Paint()
            ..color = const Color(0xFF77D8FF).withValues(alpha: juncOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    // 10. Glow layer
    final glowOp = _interp(t, _glowOpKt, _glowOpV);
    if (glowOp > 0.001) {
      final glowPaint = Paint()
        ..shader = nShader
        ..color = Colors.white.withValues(alpha: glowOp)
        ..strokeWidth = 20.0
        ..style = PaintingStyle.stroke
        ..strokeCap = StrokeCap.round
        ..strokeJoin = StrokeJoin.round
        ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 5.0);
      final glowPath = Path()
        ..moveTo(150, 370)
        ..lineTo(150, 142)
        ..lineTo(362, 370)
        ..lineTo(362, 142);
      canvas.drawPath(glowPath, glowPaint);
    }

    // 11. N Structure (strokes 1, 2, 3)
    final d1 = _interp(t, _nStroke1DashKt, _nStroke1DashV);
    final d2 = _interp(t, _nStroke2DashKt, _nStroke2DashV);
    final d3 = _interp(t, _nStroke3DashKt, _nStroke3DashV);

    final nPaint = Paint()
      ..shader = nShader
      ..strokeWidth = 10.0
      ..style = PaintingStyle.stroke
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final f1 = (1.0 - d1).clamp(0.0, 1.0);
    if (f1 > 0.001) {
      canvas.drawLine(
        const Offset(150, 370),
        Offset(150, 370 - 228 * f1),
        nPaint,
      );
    }

    final f2 = (1.0 - d2).clamp(0.0, 1.0);
    if (f2 > 0.001) {
      canvas.drawLine(
        const Offset(150, 142),
        Offset(150 + 212 * f2, 142 + 228 * f2),
        nPaint,
      );
    }

    final f3 = (1.0 - d3).clamp(0.0, 1.0);
    if (f3 > 0.001) {
      canvas.drawLine(
        const Offset(362, 370),
        Offset(362, 370 - 228 * f3),
        nPaint,
      );
    }

    // 12. Light trail
    final ltOp = _interp(t, _ltOpKt, _ltOpV);
    if (ltOp > 0.001) {
      final ltDash = _interp(t, _ltDashKt, _ltDashV);
      final head = (-ltDash).clamp(0.0, 1.0);
      final tail = (head - 0.16).clamp(0.0, 1.0);
      if (head > tail) {
        // head point calculated below
        final pTail = _getNPoint(tail);
        // Draw connecting segment
        final trailPaint = Paint()
          ..color = const Color(0xFF48D7E8).withValues(alpha: ltOp)
          ..strokeWidth = 10.0
          ..style = PaintingStyle.stroke
          ..strokeCap = StrokeCap.round
          ..strokeJoin = StrokeJoin.round;
        final trailPath = Path()..moveTo(pTail.dx, pTail.dy);
        const steps = 10;
        for (int s = 1; s <= steps; s++) {
          final u = tail + (head - tail) * (s / steps);
          final pt = _getNPoint(u);
          trailPath.lineTo(pt.dx, pt.dy);
        }
        canvas.drawPath(trailPath, trailPaint);
      }
    }

    // 13. Packets
    final pkOps = [
      _interp(t, _packet1OpKt, _packet1OpV),
      _interp(t, _packet2OpKt, _packet2OpV),
      _interp(t, _packet3OpKt, _packet3OpV),
    ];
    for (int i = 0; i < 3; i++) {
      if (pkOps[i] > 0.001) {
        final pt = _getNPoint(t);
        canvas.drawCircle(
          pt,
          4.0,
          Paint()
            ..color = const Color(0xFF48D7E8).withValues(alpha: pkOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    // 14. Node Highlights
    final nhOps = [
      _interp(t, _nh0OpKt, _nh0OpV),
      _interp(t, _nh1OpKt, _nh1OpV),
      _interp(t, _nh2OpKt, _nh2OpV),
      _interp(t, _nh3OpKt, _nh3OpV),
      _interp(t, _nh4OpKt, _nh4OpV),
    ];
    for (int i = 0; i < 5; i++) {
      if (nhOps[i] > 0.001) {
        canvas.drawCircle(
          _nhCoords[i],
          11.0,
          Paint()
            ..color = const Color(0xFF48D7E8).withValues(alpha: nhOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    // 15. Brackets
    _drawBracket(canvas, t, 0, const [Offset(96, 156), Offset(96, 96), Offset(156, 96)], _br0TrKt, _br0TrDx, _br0TrDy, _br0OpKt, _br0OpV);
    _drawBracket(canvas, t, 1, const [Offset(356, 96), Offset(416, 96), Offset(416, 156)], _br1TrKt, _br1TrDx, _br1TrDy, _br1OpKt, _br1OpV);
    _drawBracket(canvas, t, 2, const [Offset(96, 356), Offset(96, 416), Offset(156, 416)], _br2TrKt, _br2TrDx, _br2TrDy, _br2OpKt, _br2OpV);
    _drawBracket(canvas, t, 3, const [Offset(416, 356), Offset(416, 416), Offset(356, 416)], _br3TrKt, _br3TrDx, _br3TrDy, _br3OpKt, _br3OpV);

    // 16. Barcode
    final bcOps = [

      _interp(t, _bc0OpKt, _bc0OpV),
      _interp(t, _bc1OpKt, _bc1OpV),
      _interp(t, _bc2OpKt, _bc2OpV),
      _interp(t, _bc3OpKt, _bc3OpV),
      _interp(t, _bc4OpKt, _bc4OpV),
      _interp(t, _bc5OpKt, _bc5OpV),
      _interp(t, _bc6OpKt, _bc6OpV),
      _interp(t, _bc7OpKt, _bc7OpV),
      _interp(t, _bc8OpKt, _bc8OpV),
      _interp(t, _bc9OpKt, _bc9OpV),
      _interp(t, _bc10OpKt, _bc10OpV),
      _interp(t, _bc11OpKt, _bc11OpV),
      _interp(t, _bc12OpKt, _bc12OpV),
      _interp(t, _bc13OpKt, _bc13OpV),
      _interp(t, _bc14OpKt, _bc14OpV),
      _interp(t, _bc15OpKt, _bc15OpV),
      _interp(t, _bc16OpKt, _bc16OpV),
      _interp(t, _bc17OpKt, _bc17OpV),
      _interp(t, _bc18OpKt, _bc18OpV),
      _interp(t, _bc19OpKt, _bc19OpV),
      _interp(t, _bc20OpKt, _bc20OpV),
      _interp(t, _bc21OpKt, _bc21OpV),
      _interp(t, _bc22OpKt, _bc22OpV),
      _interp(t, _bc23OpKt, _bc23OpV),
      _interp(t, _bc24OpKt, _bc24OpV),
      _interp(t, _bc25OpKt, _bc25OpV),
      _interp(t, _bc26OpKt, _bc26OpV),
      _interp(t, _bc27OpKt, _bc27OpV),
      _interp(t, _bc28OpKt, _bc28OpV),
      _interp(t, _bc29OpKt, _bc29OpV),
      _interp(t, _bc30OpKt, _bc30OpV),
      _interp(t, _bc31OpKt, _bc31OpV),
      _interp(t, _bc32OpKt, _bc32OpV),
      _interp(t, _bc33OpKt, _bc33OpV),
      _interp(t, _bc34OpKt, _bc34OpV),
      _interp(t, _bc35OpKt, _bc35OpV),
      _interp(t, _bc36OpKt, _bc36OpV),
      _interp(t, _bc37OpKt, _bc37OpV),
      _interp(t, _bc38OpKt, _bc38OpV),
      _interp(t, _bc39OpKt, _bc39OpV),
      _interp(t, _bc40OpKt, _bc40OpV),
      _interp(t, _bc41OpKt, _bc41OpV),
      _interp(t, _bc42OpKt, _bc42OpV),
      _interp(t, _bc43OpKt, _bc43OpV),
      _interp(t, _bc44OpKt, _bc44OpV),
    ];
    for (int i = 0; i < _barcodeRects.length; i++) {
      if (bcOps[i] > 0.001) {
        canvas.drawRect(
          _barcodeRects[i],
          Paint()
            ..color = const Color(0xFF1687FF).withValues(alpha: bcOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    // 17. Fragments
    _drawFragment(canvas, t, 0, _fragRects[0], _fr0TrKt, _fr0TrDx, _fr0TrDy, _fr0OpKt, _fr0OpV);
    _drawFragment(canvas, t, 1, _fragRects[1], _fr1TrKt, _fr1TrDx, _fr1TrDy, _fr1OpKt, _fr1OpV);
    _drawFragment(canvas, t, 2, _fragRects[2], _fr2TrKt, _fr2TrDx, _fr2TrDy, _fr2OpKt, _fr2OpV);
    _drawFragment(canvas, t, 3, _fragRects[3], _fr3TrKt, _fr3TrDx, _fr3TrDy, _fr3OpKt, _fr3OpV);

    // 18. Beams
    final hBeamOp = _interp(t, _hBeamOpKt, _hBeamOpV);
    if (hBeamOp > 0.001) {
      final hBeamY = _interp(t, _hBeamYKt, _hBeamYV);
      canvas.drawRect(
        Rect.fromLTWH(96, hBeamY, 320, 2),
        Paint()
          ..shader = hBeamShader
          ..color = Colors.white.withValues(alpha: hBeamOp),
      );
    }

    final vBeamOp = _interp(t, _vBeamOpKt, _vBeamOpV);
    if (vBeamOp > 0.001) {
      canvas.drawRect(
        const Rect.fromLTWH(255, 96, 2, 320),
        Paint()
          ..shader = vBeamShader
          ..color = Colors.white.withValues(alpha: vBeamOp),
      );
    }

    // 19. Orbit Nodes
    final onOps = [
      _interp(t, _on0OpKt, _on0OpV),
      _interp(t, _on1OpKt, _on1OpV),
      _interp(t, _on2OpKt, _on2OpV),
      _interp(t, _on3OpKt, _on3OpV),
    ];
    final onCxs = [
      _interp(t, _on0CxKt, _on0CxV),
      _interp(t, _on1CxKt, _on1CxV),
      _interp(t, _on2CxKt, _on2CxV),
      _interp(t, _on3CxKt, _on3CxV),
    ];
    final onCys = [
      _interp(t, _on0CyKt, _on0CyV),
      _interp(t, _on1CyKt, _on1CyV),
      _interp(t, _on2CyKt, _on2CyV),
      _interp(t, _on3CyKt, _on3CyV),
    ];
    for (int i = 0; i < 4; i++) {
      if (onOps[i] > 0.001) {
        canvas.drawCircle(
          Offset(onCxs[i], onCys[i]),
          5.0,
          Paint()
            ..color = const Color(0xFF77D8FF).withValues(alpha: onOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    // 20. Nodes
    final ndOps = [
      _interp(t, _nd0OpKt, _nd0OpV),
      _interp(t, _nd1OpKt, _nd1OpV),
      _interp(t, _nd2OpKt, _nd2OpV),
      _interp(t, _nd3OpKt, _nd3OpV),
      _interp(t, _nd4OpKt, _nd4OpV),
    ];
    final ndRs = [
      _interp(t, _nd0RKt, _nd0RV),
      _interp(t, _nd1RKt, _nd1RV),
      _interp(t, _nd2RKt, _nd2RV),
      _interp(t, _nd3RKt, _nd3RV),
      _interp(t, _nd4RKt, _nd4RV),
    ];
    for (int i = 0; i < 5; i++) {
      if (ndOps[i] > 0.001 && ndRs[i] > 0.05) {
        canvas.drawCircle(
          _nodeCoords[i],
          ndRs[i],
          Paint()
            ..color = const Color(0xFF77D8FF).withValues(alpha: ndOps[i])
            ..style = PaintingStyle.fill,
        );
      }
    }

    canvas.restore();
  }

  void _drawBracket(
    Canvas canvas,
    double t,
    int index,
    List<Offset> pts,
    List<double> trKt,
    List<double> trDx,
    List<double> trDy,
    List<double> opKt,
    List<double> opV,
  ) {
    final op = _interp(t, opKt, opV);
    if (op <= 0.001) return;
    final dx = _interp(t, trKt, trDx);
    final dy = _interp(t, trKt, trDy);
    canvas.save();
    canvas.translate(dx, dy);
    final path = Path()
      ..moveTo(pts[0].dx, pts[0].dy)
      ..lineTo(pts[1].dx, pts[1].dy)
      ..lineTo(pts[2].dx, pts[2].dy);
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFF77D8FF).withValues(alpha: op)
        ..strokeWidth = 6.0
        ..style = PaintingStyle.stroke
        ..strokeCap = StrokeCap.square,
    );
    canvas.restore();
  }

  void _drawFragment(
    Canvas canvas,
    double t,
    int index,
    Rect rect,
    List<double> trKt,
    List<double> trDx,
    List<double> trDy,
    List<double> opKt,
    List<double> opV,
  ) {
    final op = _interp(t, opKt, opV);
    if (op <= 0.001) return;
    final dx = _interp(t, trKt, trDx);
    final dy = _interp(t, trKt, trDy);
    canvas.save();
    canvas.translate(dx, dy);
    canvas.drawRRect(
      RRect.fromRectAndRadius(rect, const Radius.circular(2)),
      Paint()
        ..color = const Color(0xFF1687FF).withValues(alpha: op)
        ..style = PaintingStyle.fill,
    );
    canvas.restore();
  }

